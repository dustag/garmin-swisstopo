# Decimal separator: Swiss usage (point) in German, comma in French and Italian
DECIMAL = {"fr": ",", "it": ","}


def tr(text: str, **values) -> str:
    """Text in the current language, with its {placeholders} filled."""
    out = text if language == "fr" else TEXTS[text][language]
    return out.format(**values) if values else out


def decimal(number: str) -> str:
    return number.replace(".", DECIMAL.get(language, "."))
